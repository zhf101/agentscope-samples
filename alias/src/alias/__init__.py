# -*- coding: utf-8 -*-
"""
================================================================================
Alias 包入口文件 - Python 包基础知识
================================================================================

【什么是 Python 包？】
在 Python 中，一个"包"(Package) 是一个包含 __init__.py 文件的目录。
__init__.py 文件的存在告诉 Python："这个目录是一个包，可以被导入"。

当我们执行 `import alias` 时，Python 会：
1. 找到 alias 目录
2. 执行 alias/__init__.py 中的代码
3. 让我们可以访问这个包中的内容

【包的结构示例】
alias/                      <- 这是一个包
├── __init__.py            <- 包入口文件（你现在看到的这个文件）
├── agent/                 <- 这是一个子包
│   └── __init__.py
├── runtime/               <- 这是一个子包
│   └── __init__.py
└── server/                <- 这是一个子包
    └── __init__.py

【版本号规范】
版本号通常遵循"语义化版本"(Semantic Versioning) 规范：主版本号.次版本号.修订号
- 主版本号(Major)：不兼容的 API 修改
- 次版本号(Minor)：向后兼容的功能性新增
- 修订号(Patch)：向后兼容的问题修正

"0.2.0" 表示：
- 0 = 主版本号（还在开发阶段，API 可能变化）
- 2 = 次版本号（第二个功能版本）
- 0 = 修订号（无修复）
"""

# ==============================================================================
# 版本号定义
# ==============================================================================
# __version__ 是一个约定俗成的变量名，用于存储当前包的版本号
# 用户可以通过 alias.__version__ 来查看版本
# 例如：print(alias.__version__) 会输出 "0.2.0"
__version__ = "0.2.0"

# ==============================================================================
# 导出列表 - __all__ 的作用
# ==============================================================================
# __all__ 定义了当使用 `from alias import *` 时，哪些名字会被导入
# 
# 例如：
#   from alias import *
#   # 这会导入 agent, runtime, __version__ 三个名字
# 
# 如果没有定义 __all__，`from alias import *` 会导入所有不以 _ 开头的名字
# 定义 __all__ 可以精确控制导出内容，避免导入不需要的东西
#
# 【小白理解】
# 可以把 __all__ 想象成一个"菜单"，告诉用户："这个包提供这些主要功能"
__all__ = ["agent", "runtime", "__version__"]

# ==============================================================================
# 子模块导入 - 为什么放在文件末尾？
# ==============================================================================
# 这里我们导入了两个子模块：agent 和 runtime
# 导入后，用户可以这样使用：
#   import alias
#   alias.agent.run()    # 访问 agent 子模块
#   alias.runtime.xxx    # 访问 runtime 子模块
#
# 【重要知识点：为什么导入要放在文件末尾？】
# 这是为了避免"循环导入"(Circular Import) 问题。
#
# 循环导入示例：
#   模块A 导入 模块B
#   模块B 导入 模块A
#   这样 Python 就会陷入死循环，不知道先初始化哪个模块
#
# 通过把导入放在 __init__.py 的末尾，可以确保：
# 1. 先定义好 __version__ 和 __all__
# 2. 再导入可能依赖这些变量的子模块
# 3. 避免导入时子模块找不到父模块定义的问题
#
# 【代码注释说明：# noqa】
# noqa 是 "no quality assurance" 的缩写，意思是"跳过代码质量检查"
# 
# E402 = 模块级导入不在文件顶部（我们故意放在末尾，所以要跳过这个警告）
# F401 = 导入但未使用（我们只是为了让子模块可访问，不需要直接使用）
#
# 例如：# noqa: E402, F401 表示跳过 E402 和 F401 两个检查规则
from . import agent  # noqa: E402, F401  # 导入 agent 子包
from . import runtime  # noqa: E402, F401  # 导入 runtime 子包